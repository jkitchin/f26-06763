#!/usr/bin/env python3
"""Write the icons the L19 deck uses into its style block, as CSS masks.

The deck draws an icon with <i class="ic i-NAME"></i>, where NAME is a Lucide icon
(https://lucide.dev, ISC license). This script finds every i-NAME in slides.md and writes one
CSS rule per icon between the "icons:" markers of the deck's <style> block, so the deck loads
nothing from outside and needs no extra file beside it in production.

    python3 lectures/l19/build_icons.py            # downloads lucide-static with npm pack
    LUCIDE=path/to/lucide-static/icons python3 lectures/l19/build_icons.py
"""
import os
import re
import subprocess
import tarfile
import urllib.parse
from pathlib import Path

HERE = Path(__file__).parent
DECK = HERE / "slides.md"
VERSION = "0.460.0"
BEGIN = "/* icons: generated by build_icons.py from Lucide (lucide.dev, ISC license). Do not edit by hand. */"
END = "/* icons: end */"


def icon_dir():
    if os.environ.get("LUCIDE"):
        return Path(os.environ["LUCIDE"])
    cache = HERE / ".cache" / f"lucide-static-{VERSION}"
    if not (cache / "package" / "icons").exists():
        cache.mkdir(parents=True, exist_ok=True)
        subprocess.run(["npm", "pack", f"lucide-static@{VERSION}", "--silent"], cwd=cache, check=True)
        with tarfile.open(cache / f"lucide-static-{VERSION}.tgz") as t:
            t.extractall(cache, filter="data")
    return cache / "package" / "icons"


def data_uri(svg):
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r'\s+class="[^"]*"', "", svg)
    svg = re.sub(r"\s+", " ", svg).strip().replace('"', "'").replace("currentColor", "black")
    return "data:image/svg+xml," + urllib.parse.quote(svg, safe=" '=:/;,")


def main():
    deck = DECK.read_text()
    names = sorted(set(re.findall(r'class="ic i-([a-z0-9-]+)"', deck)))
    src = icon_dir()
    missing = [n for n in names if not (src / f"{n}.svg").exists()]
    if missing:
        raise SystemExit(f"no such Lucide icon: {', '.join(missing)}")
    rules = [".ic { display: inline-block; width: 1.15em; height: 1.15em; vertical-align: -0.2em; background-color: currentColor;\n"
             "  -webkit-mask: var(--i) center / contain no-repeat; mask: var(--i) center / contain no-repeat; }"]
    rules += [f'.i-{n} {{ --i: url("{data_uri((src / f"{n}.svg").read_text())}"); }}' for n in names]
    a, b = deck.index(BEGIN) + len(BEGIN), deck.index(END)
    DECK.write_text(deck[:a] + "\n" + "\n".join(rules) + "\n" + deck[b:])
    print(f"wrote {len(names)} icons into {DECK.name}")


if __name__ == "__main__":
    main()
